use std::path::{Path, PathBuf};
use std::process::Command;

#[derive(Debug, Clone)]
pub struct BridgeType {
    pub name: String,
    pub c_type: String,
    pub lingo_type: String,
}

#[derive(Debug, Clone)]
pub struct BridgeFunction {
    pub rust_name: String,
    pub export_name: String,
    pub params: Vec<(String, BridgeType)>,
    pub ret_type: Option<BridgeType>,
}

pub struct BridgeGenerator {
    functions: Vec<BridgeFunction>,
}

impl BridgeGenerator {
    pub fn new() -> Self {
        Self {
            functions: Vec::new(),
        }
    }

    pub fn add_function(&mut self, func: BridgeFunction) {
        self.functions.push(func);
    }

    pub fn generate_rust_shim(&self) -> String {
        let mut out = String::new();
        out.push_str("// Auto-generated by lingo-bridge for Rust interop\n\n");

        for f in &self.functions {
            let mut params_str = String::new();
            let mut call_args = String::new();

            for (i, (name, ty)) in f.params.iter().enumerate() {
                if i > 0 {
                    params_str.push_str(", ");
                    call_args.push_str(", ");
                }
                params_str.push_str(&format!("{name}: {}", ty.c_type));
                call_args.push_str(name);
            }

            let ret_str = match &f.ret_type {
                Some(ty) => format!(" -> {}", ty.c_type),
                None => String::new(),
            };

            out.push_str(&format!(
                "#[no_mangle]\npub extern \"C\" fn {}({}){} {{\n    {}({})\n}}\n\n",
                f.export_name, params_str, ret_str, f.rust_name, call_args
            ));
        }

        out
    }

    pub fn generate_lingo_declarations(&self) -> String {
        let mut out = String::new();
        out.push_str("# Auto-generated Lingo foreign declarations\n\n");

        for f in &self.functions {
            let mut params_str = String::new();
            for (i, (name, ty)) in f.params.iter().enumerate() {
                if i > 0 {
                    params_str.push_str(", ");
                }
                params_str.push_str(&format!("{name}: {}", ty.lingo_type));
            }

            let ret_str = match &f.ret_type {
                Some(ty) => format!(" -> {}", ty.lingo_type),
                None => String::new(),
            };

            out.push_str(&format!("extern def {}({}){}\n", f.export_name, params_str, ret_str));
        }

        out
    }

    pub fn build_static_library(&self, crate_dir: &Path) -> Result<PathBuf, String> {
        let status = Command::new("cargo")
            .arg("build")
            .arg("--release")
            .current_dir(crate_dir)
            .status()
            .map_err(|e| format!("Failed to run cargo build: {e}"))?;

        if !status.success() {
            return Err("Cargo build for bridge library failed".into());
        }

        let target_dir = crate_dir.join("target/release");
        Ok(target_dir)
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_bridge_code_generation() {
        let mut bridge = BridgeGenerator::new();
        bridge.add_function(BridgeFunction {
            rust_name: "my_crate::fast_compute".into(),
            export_name: "lingo_fast_compute".into(),
            params: vec![
                ("a".into(), BridgeType { name: "i64".into(), c_type: "i64".into(), lingo_type: "int".into() }),
                ("b".into(), BridgeType { name: "i64".into(), c_type: "i64".into(), lingo_type: "int".into() }),
            ],
            ret_type: Some(BridgeType { name: "i64".into(), c_type: "i64".into(), lingo_type: "int".into() }),
        });

        let shim = bridge.generate_rust_shim();
        assert!(shim.contains("pub extern \"C\" fn lingo_fast_compute(a: i64, b: i64) -> i64"));

        let lingo_decl = bridge.generate_lingo_declarations();
        assert!(lingo_decl.contains("extern def lingo_fast_compute(a: int, b: int) -> int"));
    }
}
